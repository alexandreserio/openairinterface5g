/* ------------------------------------------------------------------ */
/*  Helper: clamp                                                       */
/* ------------------------------------------------------------------ */
 
static inline int clamp_int(int val, int lo, int hi)
{
    if (val < lo) return lo;
    if (val > hi) return hi;
    return val;
}
 
/* ------------------------------------------------------------------ */
/*  agc_lut_lookup()                                                    *
 *                                                                      *
 *  rsrp_dbm — measured RSRP in dBm (e.g. -97)                         *
 *  snr_db   — measured SNR  in dB  (e.g.  15)                         *
 *  Returns  — RX gain to apply (0 … 76)                               */
/* ------------------------------------------------------------------ */
 
rx_gain_t agc_lut_lookup(int rsrp_dbm, int snr_db)
{
    int rsrp_c = clamp_int(rsrp_dbm, AGC_RSRP_MIN_DBM, AGC_RSRP_MAX_DBM);
    int snr_c  = clamp_int(snr_db,   AGC_SNR_MIN_DB,   AGC_SNR_MAX_DB);
 
    int idx_r = (rsrp_c - AGC_RSRP_MIN_DBM) / AGC_RSRP_STEP_DB;
    int idx_s = (snr_c  - AGC_SNR_MIN_DB)   / AGC_SNR_STEP_DB;
 
    return rx_gain_lut[idx_r][idx_s];
}